const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'dialog-http-'));
process.env.WORKFLOW_CACHE_DIR = path.join(directory, 'workflow');
process.env.STYLE_PROFILE_CACHE_DIR = path.join(directory, 'styles');
process.env.AI_DIALOG_CACHE_DIR = path.join(directory, 'conversations');
process.env.KNOWLEDGE_UPLOAD_DIR = path.join(directory, 'uploads');
process.env.DB_PATH = ':memory:';
const express = require('express');
const { KnowledgeBase, LLMConfig } = require('../models/workflowModel');
const { StyleProfile } = require('../models/styleProfileModel');
const { Conversation, Message } = require('../models/conversationModel');
const { createAIDialogService } = require('./aiDialogService');
const { createAIDialogRouter } = require('../routes/aiDialogRoutes');
const { materialImageInput } = require('./materialImageInput');

test('HTTP: full ingestion, metadata review, vision candidates, style defaults, durable dialogue and reconnect', async t => {
  let generated = 0, hold, release;
  const service = createAIDialogService({ filename: ':memory:', messages: Message,
    invoke: async (system, input) => {
      const request = JSON.parse(input);
      if (system.includes('任务规划器')) return { content: JSON.stringify({ needsText: false, needsImages: true, imageCount: 1, productName: 'R5-Curve', imageSize: '1K', referenceView: 'back', searchQueries: ['轻量化'] }) };
      return { content: JSON.stringify([{ prompt: `Keep ${request.plan.productName} intact, minimal exhibition environment.` }]) };
    },
    generate: async params => { generated++; params.onSubmitted({ upstreamId: 'mock-id' }); if (hold) await new Promise(resolve => { release = resolve; }); return { imageUrl: '/local_storage/mock-result.png' }; },
  });
  const app = express(); app.use(express.json({ limit: '10mb' }));
  app.use('/api/ai-dialog', createAIDialogRouter({ service }));
  app.use('/api/knowledge', require('../routes/knowledgeRoutes'));
  app.use('/api/style-profiles', require('../routes/styleProfileRoutes'));
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  t.after(async () => { release?.(); await service.close(); await new Promise(resolve => server.close(resolve)); fs.rmSync(directory, { recursive: true, force: true }); });
  const request = async (url, method = 'GET', body, expected = 200) => {
    const response = await fetch(base + url, { method, headers: { 'Content-Type': 'application/json' }, body: body ? JSON.stringify(body) : undefined });
    const result = await response.json(); assert.equal(response.status, expected, JSON.stringify(result)); return result.data;
  };
  const upload = async (name, data) => { const form = new FormData(); form.append('files', new Blob([data]), name); form.append('folder', 'product'); const result = await (await fetch(base + '/api/knowledge/upload', { method: 'POST', body: form })).json(); assert.equal(result.success, true); return result.data[0]; };
  const text = 'R5-Curve 轻量化产品资料。\n'.repeat(1500) + '末尾唯一规格8KG';
  const uploaded = await upload('R5-Curve.txt', text);
  let item = await KnowledgeBase.findByPk(uploaded.id);
  assert.equal(item.content, text); assert.ok(item.content.length > 15000); assert.equal(item.metadata.parseStatus, 'ready');
  for (let i = 0; i < 105; i++) await KnowledgeBase.create({ title: `other-${i}`, content: '无关资料' });
  assert.equal((await request('/api/knowledge')).length, 106);
  const picture = await upload('R5-Curve-back.png', Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScLbtAAAAABJRU5ErkJggg==', 'base64'));
  item = await KnowledgeBase.findByPk(picture.id);
  await request(`/api/knowledge/${picture.id}`, 'PUT', { ...item, metadata: { productName: 'R5-Curve', assetRole: 'product', imageView: 'back', status: 'approved', allowExternal: true } });
  assert.ok((await materialImageInput(picture.fileUrl)).startsWith('data:image/png;base64,'));
  await assert.rejects(() => materialImageInput('/uploads/knowledge/../outside.png'));
  await request('/api/knowledge', 'POST', { title: 'invalid', content: 'x', metadata: [] }, 400);
  const failedDoc = await upload('old.doc', Buffer.from('fake binary'));
  assert.equal(failedDoc.parseStatus, 'failed'); assert.equal((await KnowledgeBase.findByPk(failedDoc.id)).metadata.status, 'draft');
  const failedPdf = await upload('scan.pdf', Buffer.from('not a pdf'));
  assert.equal(failedPdf.parseStatus, 'failed');
  const zip = new (require('adm-zip'))(); zip.addFile('word/document.xml', Buffer.from('<w:document><w:p><w:r><w:t>产品真实说明8KG</w:t></w:r></w:p></w:document>'));
  const word = await upload('product.docx', zip.toBuffer()); assert.ok((await KnowledgeBase.findByPk(word.id)).content.includes('8KG'));
  await LLMConfig.create({ provider: 'openai', name: 'mock-vision', model: 'mock-vision', api_url: 'http://127.0.0.1', api_key: 'test-only', is_default: true });
  const llm = require('./llmService'), old = llm.completeWithImages; let visionCalls = 0;
  llm.completeWithImages = async () => { visionCalls++; return { content: JSON.stringify({ description: '可见产品背面与锁扣', productName: '', assetRole: 'product', imageView: 'back' }) }; };
  t.after(() => { llm.completeWithImages = old; });
  const analyzed = await request(`/api/knowledge/${picture.id}/analyze`, 'POST');
  assert.equal(analyzed.metadata.analysis.status, 'candidate'); assert.equal(analyzed.metadata.description, undefined); assert.equal(visionCalls, 1);
  await request(`/api/knowledge/${picture.id}`, 'PUT', { ...analyzed, metadata: { ...analyzed.metadata, allowExternal: false } });
  await request(`/api/knowledge/${picture.id}/analyze`, 'POST', null, 403); assert.equal(visionCalls, 1);
  await request(`/api/knowledge/${picture.id}`, 'PUT', { ...analyzed, metadata: { ...analyzed.metadata, description: analyzed.metadata.analysis.candidate.description, allowExternal: true, analysis: { ...analyzed.metadata.analysis, status: 'reviewed' } } });
  const first = await request('/api/style-profiles', 'POST', { name: '科技风', parameters: { model: 'gpt-image-2.5-flare', brandRules: '禁止改变产品结构', dialogDefault: true } });
  const second = await request('/api/style-profiles', 'POST', { name: '极简风', parameters: { model: 'gpt-image-2.5-sunburst', dialogDefault: true } });
  assert.equal((await StyleProfile.findAll()).filter(p => p.parameters.dialogDefault).length, 1);
  assert.equal((await StyleProfile.findById(first.id)).parameters.dialogDefault, false);
  assert.equal((await request('/api/ai-dialog/options')).styles.find(p => p.id === second.id).isDefault, true);
  await request('/api/style-profiles', 'POST', { name: 'invalid', parameters: { model: 'fake' } }, 400);
  await request('/api/ai-dialog/runs', 'POST', { message: '  ' }, 400);
  hold = true;
  const payload = { message: 'R5-Curve 背面产品图', requestId: 'same-request', options: { model: 'gpt-image-2.5-flare', styleId: first.id } };
  const run = await request('/api/ai-dialog/runs', 'POST', payload);
  const duplicate = await request('/api/ai-dialog/runs', 'POST', payload); assert.equal(duplicate.id, run.id);
  assert.equal((await request('/api/ai-dialog/requests/same-request')).id, run.id);
  await request('/api/ai-dialog/requests/not-received', 'GET', null, 404);
  await request('/api/ai-dialog/runs', 'POST', { ...payload, requestId: 'new', conversationId: run.conversation_id }, 409);
  while (!release) await new Promise(resolve => setTimeout(resolve, 5));
  const controller = new AbortController(); const response = await fetch(`${base}/api/ai-dialog/runs/${run.id}/events`, { signal: controller.signal });
  const reader = response.body.getReader(); assert.ok((await reader.read()).value.length); controller.abort(); await reader.cancel().catch(() => {});
  assert.equal(service.get(run.id).status, 'running');
  release(); await service.wait(run.id);
  const done = await request(`/api/ai-dialog/runs/${run.id}`);
  assert.equal(done.status, 'completed'); assert.equal(done.state.submitted.upstreamId, 'mock-id'); assert.equal(generated, 1);
  assert.equal(done.result.plan.model, 'gpt-image-2.5-flare');
  assert.ok(done.result.sources.some(source => source.id === picture.id));
  const restored = await request(`/api/ai-dialog/conversations/${run.conversation_id}`);
  assert.equal(restored.latestRun.id, run.id); assert.equal(restored.messages.at(-1).attachments.length, 1); assert.equal(restored.messages.at(-1).metadata.style.name, '科技风');
  const stream = await fetch(`${base}/api/ai-dialog/runs/${run.id}/events?after=${done.events[0].seq}`); const events = await stream.text(); assert.ok(events.includes('event: done')); assert.ok(!events.includes(`id: ${done.events[0].seq}\n`));
  const doneDuplicate = await request('/api/ai-dialog/runs', 'POST', payload); assert.equal(doneDuplicate.id, run.id); assert.equal(generated, 1);
  await request('/api/ai-dialog/conversations/invalid..id', 'GET', null, 400);
  assert.equal((await Conversation.findAll()).length, 1);
});
